"""#322 steps 2, 3 and 6: one pinned tree-sitter CLI generates every vendored parser, CI proves it,
and no doc or workflow tells anyone to run another version.

These checks need no CLI. CI's regeneration step (`scripts/regen-vendored-parsers.py` then
`git diff --exit-code`) is the byte-for-byte proof; this file proves that step exists, runs on
every grammar, and agrees with the pin.
"""

import importlib.util
from pathlib import Path
import re
import unittest

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "crates/wicked-estate-extract/vendor"
SCRIPT = ROOT / "scripts/regen-vendored-parsers.py"


def regen():
    spec = importlib.util.spec_from_file_location("regen_vendored_parsers", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class ParserRegenerationTests(unittest.TestCase):
    def setUp(self):
        self.assertTrue(SCRIPT.is_file(), f"{SCRIPT.relative_to(ROOT)} is missing")
        self.regen = regen()

    def test_every_grammar_is_found(self):
        # 11 trees with a generated grammar, cfml holding two; the COBOL scanner tree has none.
        found = [str(d.relative_to(VENDOR)) for d in self.regen.grammar_dirs()]
        self.assertEqual(len(found), 13, found)

    def test_every_committed_parser_is_regenerated(self):
        # Inventoried independently of the script's discovery: every parser.c in vendor/ must be
        # one the script regenerates, so a parser with no grammar.json cannot hide from CI.
        committed = sorted(p.parent.parent for p in VENDOR.glob("**/parser.c"))
        self.assertEqual(committed, self.regen.grammar_dirs())
        self.assertEqual(self.regen.orphan_parsers(), [])

    def test_a_parser_with_no_grammar_is_reported(self):
        import shutil, tempfile
        with tempfile.TemporaryDirectory() as tmp:
            vendor = Path(tmp) / "vendor"
            (vendor / "tree-sitter-x" / "unchecked" / "src").mkdir(parents=True)
            (vendor / "tree-sitter-x" / "unchecked" / "src" / "parser.c").write_text("/* stale */\n")
            (vendor / "tree-sitter-y" / "src").mkdir(parents=True)
            (vendor / "tree-sitter-y" / "src" / "grammar.json").write_text("{}")
            (vendor / "tree-sitter-y" / "src" / "parser.c").write_text("")
            (vendor / "tree-sitter-y" / "parser.c").write_text("")
            self.assertEqual(self.regen.orphan_parsers(vendor),
                             ["tree-sitter-x/unchecked/src/parser.c", "tree-sitter-y/parser.c"])

    def test_every_crate_ships_its_regeneration_config(self):
        import tomllib
        for cargo in sorted(VENDOR.glob("*/Cargo.toml")):
            if cargo.parent.name in self.regen.NOT_YET_REGENERATED:
                continue
            include = tomllib.loads(cargo.read_text())["package"].get("include")
            self.assertIn("tree-sitter.json", include or ["tree-sitter.json"], cargo.parent.name)

    def test_only_vbscript_waits_for_its_own_regeneration_pr(self):
        # Each entry is one PR gated on its extraction output; the list must only shrink.
        self.assertEqual(sorted(self.regen.NOT_YET_REGENERATED), ["tree-sitter-vbscript"])
        self.assertEqual(len(self.regen.regenerated_dirs()), 12)

    def test_every_grammar_has_a_regeneration_config(self):
        missing = [str(d.relative_to(VENDOR)) for d in self.regen.regenerated_dirs() if not self.regen.has_config(d)]
        self.assertEqual(missing, [], "without tree-sitter.json the CLI falls back to ABI 14")

    def test_every_parser_is_the_pinned_cli_at_abi_15(self):
        header = f"/* Automatically @generated by tree-sitter v{self.regen.PIN} */"
        wrong = []
        for d in self.regen.regenerated_dirs():
            text = (d / "src/parser.c").read_text(errors="replace")
            if not text.startswith(header + "\n") or "\n#define LANGUAGE_VERSION 15\n" not in text:
                wrong.append(str(d.relative_to(VENDOR)))
        self.assertEqual(wrong, [])

    def test_upstream_grammar_js_is_never_run(self):
        # Only trees PROVENANCE records as authored here get `generate` from grammar.js.
        in_house = self.regen.in_house_trees()
        self.assertNotIn("tree-sitter-cfml", in_house)
        for tree in ("tree-sitter-vb6", "tree-sitter-vba", "tree-sitter-vbscript", "tree-sitter-cobol-scanner"):
            self.assertNotIn(tree, in_house)
        self.assertIn("tree-sitter-rpg", in_house)
        self.assertIn("tree-sitter-apexlang", in_house)

    def test_ci_regenerates_every_parser_and_fails_on_a_diff(self):
        ci = (ROOT / ".github/workflows/ci.yml").read_text()
        step = re.search(r"run: python3 scripts/regen-vendored-parsers\.py && git diff --exit-code -- crates/wicked-estate-extract/vendor\n", ci)
        self.assertIsNotNone(step, "CI must run the regeneration and fail on any diff")

    def test_every_cli_reference_is_the_pin(self):
        pin = self.regen.PIN
        stray = []
        for rel in (".github/workflows/ci.yml", "FEATURES.md", "PLUGIN.md", "docs/add-lang.md",
                    "crates/wicked-estate-extract/vendor/PROVENANCE.md"):
            path = ROOT / rel
            if not path.is_file():
                continue
            text = path.read_text()
            stray += [f"{rel}: {m.group(0)}" for m in re.finditer(r"tree-sitter-cli@([\w^~-]+(?:\.[\w^~-]+)*)", text)
                      if m.group(1) != pin]
            # an unpinned npx run takes whatever version npm serves that day
            stray += [f"{rel}: {m.group(0)}" for m in re.finditer(r"npx (?:--yes )?tree-sitter(?:-cli)?(?![-\w@])[^\n`]*", text)]
            stray += [f"{rel}: {m.group(0)}" for m in re.finditer(r"--abi[ =]1[0-4]\b", text)]
        self.assertEqual(stray, [])


if __name__ == "__main__":
    unittest.main()
